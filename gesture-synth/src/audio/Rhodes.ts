/*
|--------------------------------------------------------------------------
| Rhodes.ts
|--------------------------------------------------------------------------
|
| Tone.js Rhodes-style instrument.
|
| Responsibilities:
|
|   - Generate the actual sound
|   - Play notes
|   - Release notes
|   - Change volume
|   - Change filter
|
| It does NOT:
|
|   - Detect gestures
|   - Generate chords
|   - Manage React state
|
|--------------------------------------------------------------------------
*/

import * as Tone from "tone";

import type {
  Instrument,
} from "./Instrument";


export class Rhodes
  implements Instrument {

  /*
  |--------------------------------------------------------------------------
  | SYNTH
  |--------------------------------------------------------------------------
  */

  private synth:
    Tone.PolySynth;


  /*
  |--------------------------------------------------------------------------
  | FILTER
  |--------------------------------------------------------------------------
  */

  private filter:
    Tone.Filter;


  /*
  |--------------------------------------------------------------------------
  | TREMOLO
  |--------------------------------------------------------------------------
  */

  private tremolo:
    Tone.Tremolo;


  /*
  |--------------------------------------------------------------------------
  | REVERB
  |--------------------------------------------------------------------------
  */

  private reverb:
    Tone.Reverb;


  /*
  |--------------------------------------------------------------------------
  | ACTIVE NOTES
  |--------------------------------------------------------------------------
  |
  | These are the notes currently sounding.
  |
  |--------------------------------------------------------------------------
  */

  private activeNotes:
    string[] = [];


  /*
  |--------------------------------------------------------------------------
  | CONSTRUCTOR
  |--------------------------------------------------------------------------
  */

  constructor() {

    /*
    |--------------------------------------------------------------------------
    | FILTER
    |--------------------------------------------------------------------------
    */

    this.filter =
      new Tone.Filter({
        type: "lowpass",
        frequency: 5000,
        rolloff: -24,
      });


    /*
    |--------------------------------------------------------------------------
    | TREMOLO
    |--------------------------------------------------------------------------
    */

    this.tremolo =
      new Tone.Tremolo({
        frequency: 4.5,
        depth: 0.15,
        wet: 0.2,
      }).start();


    /*
    |--------------------------------------------------------------------------
    | REVERB
    |--------------------------------------------------------------------------
    */

    this.reverb =
      new Tone.Reverb({
        decay: 2,
        wet: 0.2,
      });


    /*
    |--------------------------------------------------------------------------
    | SYNTH
    |--------------------------------------------------------------------------
    */

    this.synth =
      new Tone.PolySynth(
        Tone.Synth,
        {
          oscillator: {
            type: "triangle",
          },

          envelope: {
            attack: 0.02,
            decay: 0.25,
            sustain: 0.55,
            release: 1.2,
          },
        }
      );


    /*
    |--------------------------------------------------------------------------
    | AUDIO CHAIN
    |--------------------------------------------------------------------------
    |
    | Synth
    |   ↓
    | Filter
    |   ↓
    | Tremolo
    |   ↓
    | Reverb
    |   ↓
    | Destination
    |
    |--------------------------------------------------------------------------
    */

    this.synth
      .connect(
        this.filter
      )
      .connect(
        this.tremolo
      )
      .connect(
        this.reverb
      )
      .toDestination();

  }


  /*
  |--------------------------------------------------------------------------
  | PLAY
  |--------------------------------------------------------------------------
  |
  | IMPORTANT:
  |
  | This performs a DIFFERENTIAL chord update.
  |
  | Example:
  |
  | Current:
  |
  |   C4 E4 G4
  |
  | New:
  |
  |   C4 F4 G4
  |
  | Only:
  |
  |   E4 → released
  |   F4 → attacked
  |
  | C4 and G4 continue sounding.
  |
  |--------------------------------------------------------------------------
  */

  play(
    notes: string[]
  ): void {

    /*
    |--------------------------------------------------------------------------
    | EMPTY CHORD
    |--------------------------------------------------------------------------
    */

    if (
      notes.length === 0
    ) {

      return;

    }


    /*
    |--------------------------------------------------------------------------
    | NORMALIZE
    |--------------------------------------------------------------------------
    |
    | Remove duplicates and sort so that
    | comparison is deterministic.
    |
    |--------------------------------------------------------------------------
    */

    const nextNotes =
      Array.from(
        new Set(
          notes
        )
      ).sort();


    /*
    |--------------------------------------------------------------------------
    | CURRENT NOTES
    |--------------------------------------------------------------------------
    */

    const currentNotes =
      this.activeNotes;


    /*
    |--------------------------------------------------------------------------
    | FIND NOTES TO RELEASE
    |--------------------------------------------------------------------------
    |
    | Present before.
    | Not present anymore.
    |
    |--------------------------------------------------------------------------
    */

    const notesToRelease =
      currentNotes.filter(
        note =>
          !nextNotes.includes(
            note
          )
      );


    /*
    |--------------------------------------------------------------------------
    | FIND NOTES TO ATTACK
    |--------------------------------------------------------------------------
    |
    | New note.
    | Wasn't already sounding.
    |
    |--------------------------------------------------------------------------
    */

    const notesToAttack =
      nextNotes.filter(
        note =>
          !currentNotes.includes(
            note
          )
      );


    /*
    |--------------------------------------------------------------------------
    | NOTHING CHANGED
    |--------------------------------------------------------------------------
    */

    if (
      notesToRelease.length === 0 &&
      notesToAttack.length === 0
    ) {

      return;

    }


    /*
    |--------------------------------------------------------------------------
    | RELEASE REMOVED NOTES
    |--------------------------------------------------------------------------
    */

    if (
      notesToRelease.length > 0
    ) {

      this.synth.triggerRelease(
        notesToRelease
      );

    }


    /*
    |--------------------------------------------------------------------------
    | ATTACK NEW NOTES
    |--------------------------------------------------------------------------
    */

    if (
      notesToAttack.length > 0
    ) {

      this.synth.triggerAttack(
        notesToAttack
      );

    }


    /*
    |--------------------------------------------------------------------------
    | UPDATE ACTIVE STATE
    |--------------------------------------------------------------------------
    */

    this.activeNotes =
      nextNotes;

  }


  /*
  |--------------------------------------------------------------------------
  | STOP
  |--------------------------------------------------------------------------
  |
  | Release every currently active note.
  |
  |--------------------------------------------------------------------------
  */

  stop(): void {

    if (
      this.activeNotes.length === 0
    ) {

      return;

    }


    this.synth.triggerRelease(
      this.activeNotes
    );


    this.activeNotes =
      [];

  }


  /*
  |--------------------------------------------------------------------------
  | VOLUME
  |--------------------------------------------------------------------------
  |
  | Input:
  |
  |   0 → silent
  |   1 → maximum
  |
  |--------------------------------------------------------------------------
  */

  setVolume(
    value: number
  ): void {

    const safeValue =
      Math.max(
        0.001,
        Math.min(
          1,
          value
        )
      );


    this.synth.volume.rampTo(
      Tone.gainToDb(
        safeValue
      ),
      0.05
    );

  }


  /*
  |--------------------------------------------------------------------------
  | FILTER
  |--------------------------------------------------------------------------
  */

  setFilter(
    frequency: number
  ): void {

    const safeFrequency =
      Math.max(
        100,
        Math.min(
          20000,
          frequency
        )
      );


    this.filter.frequency.rampTo(
      safeFrequency,
      0.08
    );

  }

}
/*
|--------------------------------------------------------------------------
| Rhodes.ts
|--------------------------------------------------------------------------
|
| Tone.js Rhodes-style synthesized instrument.
|
| Responsibilities:
|
|   - Generate Rhodes-style sound
|   - Play notes
|   - Release notes
|   - Change volume
|   - Change filter
|   - Dispose all Tone.js resources
|
|--------------------------------------------------------------------------
*/

import * as Tone from "tone";

import type { Instrument } from "./Instrument";

export class Rhodes implements Instrument {
  /*
  |--------------------------------------------------------------------------
  | SYNTH
  |--------------------------------------------------------------------------
  */

  private synth: Tone.PolySynth;

  /*
  |--------------------------------------------------------------------------
  | FILTER
  |--------------------------------------------------------------------------
  */

  private filter: Tone.Filter;

  /*
  |--------------------------------------------------------------------------
  | TREMOLO
  |--------------------------------------------------------------------------
  */

  private tremolo: Tone.Tremolo;

  /*
  |--------------------------------------------------------------------------
  | REVERB
  |--------------------------------------------------------------------------
  */

  private reverb: Tone.Reverb;

  /*
  |--------------------------------------------------------------------------
  | ACTIVE NOTES
  |--------------------------------------------------------------------------
  */

  private activeNotes: string[] = [];

  /*
  |--------------------------------------------------------------------------
  | CONSTRUCTOR
  |--------------------------------------------------------------------------
  */

  constructor() {
    /*
    |--------------------------------------------------------------------------
    | FILTER
    |--------------------------------------------------------------------------
    */

    this.filter = new Tone.Filter({
      type: "lowpass",

      frequency: 5000,

      rolloff: -24,

      Q: 0.7,
    });

    /*
    |--------------------------------------------------------------------------
    | TREMOLO
    |--------------------------------------------------------------------------
    */

    this.tremolo = new Tone.Tremolo({
      frequency: 4.5,

      depth: 0.15,

      wet: 0.2,
    });

    /*
    |--------------------------------------------------------------------------
    | START TREMOLO
    |--------------------------------------------------------------------------
    */

    this.tremolo.start();

    /*
    |--------------------------------------------------------------------------
    | REVERB
    |--------------------------------------------------------------------------
    */

    this.reverb = new Tone.Reverb({
      decay: 2,

      wet: 0.2,
    });

    /*
    |--------------------------------------------------------------------------
    | SYNTH
    |--------------------------------------------------------------------------
    |
    | Triangle oscillator gives the Rhodes a warm base.
    |
    |--------------------------------------------------------------------------
    */

    this.synth = new Tone.PolySynth(Tone.Synth, {
      oscillator: {
        type: "triangle",
      },

      envelope: {
        attack: 0.02,

        decay: 0.25,

        sustain: 0.55,

        release: 1.2,
      },
    });

    /*
    |--------------------------------------------------------------------------
    | AUDIO CHAIN
    |--------------------------------------------------------------------------
    |
    | Synth
    |   ↓
    | Filter
    |   ↓
    | Tremolo
    |   ↓
    | Reverb
    |   ↓
    | Destination
    |
    |--------------------------------------------------------------------------
    */

    this.synth
      .connect(this.filter)
      .connect(this.tremolo)
      .connect(this.reverb)
      .toDestination();
  }

  /*
  |--------------------------------------------------------------------------
  | PLAY
  |--------------------------------------------------------------------------
  |
  | Differential chord update.
  |
  |--------------------------------------------------------------------------
  */

  play(notes: string[]): void {
    /*
    |--------------------------------------------------------------------------
    | EMPTY CHORD
    |--------------------------------------------------------------------------
    */

    if (notes.length === 0) {
      return;
    }

    /*
    |--------------------------------------------------------------------------
    | NORMALIZE NOTES
    |--------------------------------------------------------------------------
    */

    const nextNotes = Array.from(new Set(notes)).sort();

    /*
    |--------------------------------------------------------------------------
    | CURRENT NOTES
    |--------------------------------------------------------------------------
    */

    const currentNotes = this.activeNotes;

    /*
    |--------------------------------------------------------------------------
    | RELEASE REMOVED NOTES
    |--------------------------------------------------------------------------
    */

    const notesToRelease = currentNotes.filter(
      (note) => !nextNotes.includes(note),
    );

    /*
    |--------------------------------------------------------------------------
    | ATTACK NEW NOTES
    |--------------------------------------------------------------------------
    */

    const notesToAttack = nextNotes.filter(
      (note) => !currentNotes.includes(note),
    );

    /*
    |--------------------------------------------------------------------------
    | NOTHING CHANGED
    |--------------------------------------------------------------------------
    */

    if (notesToRelease.length === 0 && notesToAttack.length === 0) {
      return;
    }

    /*
    |--------------------------------------------------------------------------
    | RELEASE
    |--------------------------------------------------------------------------
    */

    if (notesToRelease.length > 0) {
      this.synth.triggerRelease(notesToRelease);
    }

    /*
    |--------------------------------------------------------------------------
    | ATTACK
    |--------------------------------------------------------------------------
    */

    if (notesToAttack.length > 0) {
      this.synth.triggerAttack(notesToAttack);
    }

    /*
    |--------------------------------------------------------------------------
    | UPDATE STATE
    |--------------------------------------------------------------------------
    */

    this.activeNotes = nextNotes;
  }

  /*
  |--------------------------------------------------------------------------
  | STOP
  |--------------------------------------------------------------------------
  */

  stop(): void {
    if (this.activeNotes.length === 0) {
      return;
    }

    this.synth.triggerRelease(this.activeNotes);

    this.activeNotes = [];
  }

  /*
  |--------------------------------------------------------------------------
  | VOLUME
  |--------------------------------------------------------------------------
  */

  setVolume(value: number): void {
    const safeValue = Math.max(0.001, Math.min(1, value));

    this.synth.volume.rampTo(Tone.gainToDb(safeValue), 0.05);
  }

  /*
  |--------------------------------------------------------------------------
  | FILTER
  |--------------------------------------------------------------------------
  */

  setFilter(frequency: number): void {
    const safeFrequency = Math.max(100, Math.min(20000, frequency));

    this.filter.frequency.rampTo(safeFrequency, 0.08);
  }

  /*
  |--------------------------------------------------------------------------
  | DISPOSE
  |--------------------------------------------------------------------------
  |
  | Required by Instrument.ts.
  |
  | This is important when switching:
  |
  |   Rhodes → Piano
  |
  | Without disposing these nodes, the old Rhodes can remain connected
  | to the audio graph and cause memory/audio leaks.
  |
  |--------------------------------------------------------------------------
  */

  dispose(): void {
    /*
    |--------------------------------------------------------------------------
    | Stop active notes
    |--------------------------------------------------------------------------
    */

    this.stop();

    /*
    |--------------------------------------------------------------------------
    | Stop tremolo LFO
    |--------------------------------------------------------------------------
    */

    this.tremolo.stop();

    /*
    |--------------------------------------------------------------------------
    | Dispose Tone.js nodes
    |--------------------------------------------------------------------------
    */

    this.synth.dispose();

    this.filter.dispose();

    this.tremolo.dispose();

    this.reverb.dispose();
  }
}
